using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEngine;

public static class TermometroWebGLBuild
{
    [MenuItem("Termómetro de la Tierra/Compilar WebGL")]
    public static void BuildWebGL()
    {
        var scenes = EditorBuildSettings.scenes
            .Where(scene => scene.enabled)
            .Select(scene => scene.path)
            .ToArray();

        if (scenes.Length == 0)
        {
            Debug.LogError("[Termómetro] No hay escenas habilitadas en Build Settings.");
            return;
        }

        var projectRoot = Directory.GetParent(Application.dataPath)?.FullName;
        if (string.IsNullOrEmpty(projectRoot))
        {
            Debug.LogError("[Termómetro] No se pudo resolver la carpeta raíz del proyecto.");
            return;
        }

        var buildRoot = Path.Combine(projectRoot, "Build");
        var outputDirectory = Path.Combine(buildRoot, "WebGL");
        var markerPath = Path.Combine(buildRoot, ".termometro-webgl-generated");

        if (Directory.Exists(outputDirectory))
        {
            if (File.Exists(markerPath))
            {
                Directory.Delete(outputDirectory, true);
            }
            else if (Directory.EnumerateFileSystemEntries(outputDirectory).Any())
            {
                Debug.LogError($"[Termómetro] La carpeta de salida ya existe y no fue creada por este comando: {outputDirectory}");
                return;
            }
        }

        Directory.CreateDirectory(outputDirectory);
        Directory.CreateDirectory(buildRoot);
        File.WriteAllText(markerPath, "Generated by TermometroWebGLBuild.cs");

        var report = BuildPipeline.BuildPlayer(new BuildPlayerOptions
        {
            scenes = scenes,
            locationPathName = outputDirectory,
            target = BuildTarget.WebGL,
            options = BuildOptions.None
        });

        var summary = report.summary;
        if (summary.result == BuildResult.Succeeded)
        {
            Debug.Log($"[Termómetro] WebGL compilado correctamente: {summary.totalSize / (1024f * 1024f):0.0} MB en {summary.totalTime} → {outputDirectory}");
        }
        else
        {
            Debug.LogError($"[Termómetro] Falló la compilación WebGL ({summary.result}). Revisa Console y Editor.log. Salida: {outputDirectory}");
        }
    }
}
